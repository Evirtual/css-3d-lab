/**
 * Puts the capture fonts where the site can serve them, and writes the small module that fetches
 * them when someone actually exports.
 *
 * WHY THE FONTS TRAVEL WITH A CAPTURED SCENE. The capture serializes the families the browser
 * resolved -- `system-ui`, `ui-monospace`, `Consolas` -- and no font files, so whichever browser
 * draws it uses whatever it has installed. On a Windows laptop that is Segoe UI and Consolas; on
 * the Cloudflare Worker's Linux browser it is neither, so glyphs come out wider, `4242` runs off
 * the edge of the payment card and a name that fitted on one line wraps onto two. That shipped to
 * the live site on 2026-09-25.
 *
 * WHY THEY ARE FETCHED AND NOT BUNDLED. The first fix inlined 119 KB of base64 into the module that
 * mounts the export dialog, which the page preloads -- so every visitor downloaded the fonts to
 * look at a gallery, and the heaviest page went from about 254 KB to 373 KB against a 288 KB
 * budget. check-seo caught it. Now the woff2 files are served as files, fetched once when the
 * dialog first needs them, and cached for the rest of the session.
 *
 *   node scripts/generate-capture-fonts.mjs   ->  public/fonts/*.woff2 + src/fonts/capture-fonts.ts
 */
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './model-sources.mjs';

const FACES = [
  { family: 'Inter', weight: 400, file: 'inter-latin-400.woff2' },
  { family: 'Inter', weight: 700, file: 'inter-latin-700.woff2' },
  { family: 'JetBrains Mono', weight: 400, file: 'jetbrains-mono-latin-400.woff2' },
  { family: 'JetBrains Mono', weight: 600, file: 'jetbrains-mono-latin-600.woff2' },
];

mkdirSync(join(ROOT, 'public', 'fonts'), { recursive: true });
let bytes = 0;
// A hash of each face's bytes goes into the generated module, so that scripts/fingerprint.mjs --
// which reads files, and for which a woff2 is not text -- stales every export result when a face
// is replaced. The export is a picture of text; a different face is a different picture.
const marks = [];
for (const f of FACES) {
  const from = join(ROOT, 'src', 'fonts', f.file);
  const buf = readFileSync(from);
  bytes += buf.length;
  marks.push(`${f.file} ${createHash('sha1').update(buf).digest('hex').slice(0, 12)} ${buf.length}b`);
  copyFileSync(from, join(ROOT, 'public', 'fonts', f.file));
}

writeFileSync(join(ROOT, 'src', 'fonts', 'capture-fonts.ts'),
  `// Generated by scripts/generate-capture-fonts.mjs. Do not edit.\n`
  + `// Inter and JetBrains Mono, latin. Fetched when the export dialog first needs them and embedded\n`
  + `// in the captured scene as data URIs, so every renderer draws the same glyphs. See the script.\n`
  + `//\n`
  + `// The faces themselves, by content. scripts/fingerprint.mjs reads files as text and a woff2 is\n`
  + `// not text, so this line is how replacing a face stales every export result: the export is a\n`
  + `// picture of text, and a different face is a different picture.\n`
  + marks.map((m) => `// ${m}\n`).join('')
  + `const FACES = ${JSON.stringify(FACES)};\n\n`
  + `/*\n`
  + ` * WHERE THE FILES ARE, and why this is a variable and not written inline below.\n`
  + ` *\n`
  + ` * vite.config's base is './', so import.meta.env.BASE_URL is './' and resolves against the\n`
  + ` * DOCUMENT: from a model page at /models/<id>/ that asks for /models/<id>/fonts/... and 404s.\n`
  + ` * The module is the only fixed point. The bundle puts it under <base>/assets/, so ../fonts/ is\n`
  + ` * <base>/fonts/; in dev it is /src/fonts/, where the same files sit. Both serve the real woff2.\n`
  + ` *\n`
  + ` * It is a VARIABLE because vite rewrites \`new URL(<template>, import.meta.url)\` into a lookup\n`
  + ` * over a glob of this folder, keyed by the literal it saw:\n`
  + ` *\n`
  + ` *   new URL({"./inter-latin-400.woff2": u1, ...}[\`../fonts/\${f.file}\`], import.meta.url)\n`
  + ` *\n`
  + ` * Our key is "../fonts/inter-latin-400.woff2" and the map's are "./inter-latin-400.woff2", so\n`
  + ` * every lookup missed, undefined went into the URL, and the server answered index.html with a\n`
  + ` * 200. A variable second argument is not a pattern vite rewrites.\n`
  + ` */\n`
  + `const HERE = import.meta.url;\n\n`
  + `let css = '';\n\n`
  + `/** The @font-face rules, or '' until they have been fetched. Synchronous on purpose: the scene\n`
  + ` *  is built from a laid-out DOM and cannot wait. Callers await ensureCaptureFonts() first. */\n`
  + `export const captureFontCss = (): string => css;\n\n`
  + `/** Fetches the faces once. A failure is not fatal -- the export still happens, with whatever\n`
  + ` *  fonts the renderer has, which is exactly the old behaviour and better than no picture. */\n`
  + `export async function ensureCaptureFonts(): Promise<void> {\n`
  + `  if (css) return;\n`
  + `  try {\n`
  + `    const parts = await Promise.all(FACES.map(async (f) => {\n`
  + `      const r = await fetch(new URL(\`../fonts/\${f.file}\`, HERE).href);\n`
  + `      if (!r.ok) throw new Error(\`\${r.status} \${f.file}\`);\n`
  + `      const b = new Uint8Array(await r.arrayBuffer());\n`
  + `      // A 200 is not proof that a font came back. A dev server and most static hosts answer an\n`
  + `      // unknown path with index.html and a 200, and an HTML page base64'd into a src:url() is a\n`
  + `      // face that never loads -- which is how this shipped inert without a word. wOF2 is woff2's\n`
  + `      // magic number, and checking it turns a wrong picture into a message.\n`
  + `      if (b[0] !== 0x77 || b[1] !== 0x4f || b[2] !== 0x46 || b[3] !== 0x32) {\n`
  + `        throw new Error(\`\${f.file} is not a woff2: \${b.length} bytes starting \${[...b.subarray(0, 4)].join(',')}\`);\n`
  + `      }\n`
  + `      let s = '';\n`
  + `      for (let i = 0; i < b.length; i++) s += String.fromCharCode(b[i]);\n`
  + `      return \`@font-face{font-family:"\${f.family}";font-style:normal;font-weight:\${f.weight};font-display:block;src:url(data:font/woff2;base64,\${btoa(s)}) format("woff2")}\`;\n`
  + `    }));\n`
  + `    css = parts.join('');\n`
  + `  } catch (e) {\n`
  + `    // Said out loud, because silence here is a wrong picture: every export is then drawn with\n`
  + `    // whatever fonts the renderer happens to have, which is the bug the fonts were added to fix.\n`
  + `    console.error('capture fonts: not embedded, so this export is drawn with whatever fonts the renderer has —', e);\n`
  + `    css = '';\n`
  + `  }\n`
  + `}\n`);

console.log(`capture fonts: ${FACES.length} faces, ${(bytes / 1024).toFixed(0)} KB served from public/fonts/, fetched on demand`);
