/**
 * Turns the capture fonts into a module the page can embed in a captured scene.
 *
 * WHY THE FONTS TRAVEL WITH THE SCENE. A captured page names the families the model asked for --
 * `system-ui`, `ui-monospace`, `Consolas` -- and carries no font files, so whichever browser draws
 * it uses whatever it happens to have installed. On this laptop that is Segoe UI and Consolas; on
 * the Cloudflare Worker's Linux browser it is neither, so the glyphs come out wider, `4242` runs
 * off the edge of the payment card and a name that fitted on one line wraps onto two.
 *
 * That was shipped to the live site on 2026-09-25 and found by a person opening the dialog, because
 * every check ran against the LOCAL service and nothing ever compared the two renderers.
 *
 * So the scene carries its own fonts, as data URIs, and both renderers draw the same glyphs.
 *
 *   node scripts/generate-capture-fonts.mjs   ->  src/fonts/capture-fonts.ts
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './model-sources.mjs';

const FONTS = [
  ['CaptureSans', 400, 'inter-latin-400.woff2'],
  ['CaptureSans', 700, 'inter-latin-700.woff2'],
  ['CaptureMono', 400, 'jetbrains-mono-latin-400.woff2'],
  ['CaptureMono', 600, 'jetbrains-mono-latin-600.woff2'],
];

let css = '';
let bytes = 0;
for (const [family, weight, file] of FONTS) {
  const buf = readFileSync(join(ROOT, 'src', 'fonts', file));
  bytes += buf.length;
  css += `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:block;`
    + `src:url(data:font/woff2;base64,${buf.toString('base64')}) format("woff2")}`;
}


writeFileSync(join(ROOT, 'src', 'fonts', 'capture-fonts.ts'),
  `// Generated by scripts/generate-capture-fonts.mjs from src/fonts/. Do not edit.\n`
  + `// Inter and JetBrains Mono, latin, embedded so a captured scene draws the same glyphs in every\n`
  + `// renderer. See the script for why this exists.\n`
  + `export const CAPTURE_FONT_CSS = ${JSON.stringify(css)};\n`);

console.log(`capture-fonts.ts: ${FONTS.length} faces, ${(bytes / 1024).toFixed(0)} KB of woff2, ${(css.length / 1024).toFixed(0)} KB of CSS`);
